"""USB bus device discovery and audio device matching (no hardcoded radio names)."""
from __future__ import annotations

import re
import sys
from typing import Any, Dict, List, Optional

import serial.tools.list_ports
import sounddevice as sd

if sys.platform == "win32":
    import winreg


def _read_usb_com_registry() -> Dict[str, Dict[str, str]]:
    """Read Windows USB registry to obtain exact USB instance IDs and bus strings per COM port."""
    mapping: Dict[str, Dict[str, str]] = {}
    if sys.platform != "win32":
        return mapping
    try:
        usb_root = winreg.OpenKey(winreg.HKEY_LOCAL_MACHINE, r"SYSTEM\CurrentControlSet\Enum\USB")
    except OSError:
        return mapping

    try:
        num_vidpid = winreg.QueryInfoKey(usb_root)[0]
        for i in range(num_vidpid):
            vidpid = winreg.EnumKey(usb_root, i)
            try:
                sub = winreg.OpenKey(usb_root, vidpid)
            except OSError:
                continue
            try:
                num_inst = winreg.QueryInfoKey(sub)[0]
                for j in range(num_inst):
                    inst = winreg.EnumKey(sub, j)
                    try:
                        dev = winreg.OpenKey(sub, inst)
                    except OSError:
                        continue
                    try:
                        port_name = ""
                        try:
                            dp = winreg.OpenKey(dev, "Device Parameters")
                            port_name, _ = winreg.QueryValueEx(dp, "PortName")
                            winreg.CloseKey(dp)
                        except OSError:
                            pass

                        if port_name:
                            def _q(val_name: str) -> str:
                                try:
                                    v, _ = winreg.QueryValueEx(dev, val_name)
                                    return str(v)
                                except OSError:
                                    return ""

                            mapping[port_name.upper()] = {
                                "vidpid": vidpid,
                                "instance_id": inst,
                                "friendly_name": _q("FriendlyName"),
                                "device_desc": _q("DeviceDesc"),
                                "mfg": _q("Mfg"),
                                "location": _q("LocationInformation"),
                            }
                    finally:
                        winreg.CloseKey(dev)
            finally:
                winreg.CloseKey(sub)
    finally:
        winreg.CloseKey(usb_root)

    return mapping


def extract_model_from_usb_bus(usb_info: Dict[str, str]) -> Dict[str, str]:
    """Extract radio model and serial solely from USB bus descriptors (never hardcoded)."""
    inst = usb_info.get("instance_id", "").strip()
    friendly = usb_info.get("friendly_name", "").strip()
    desc = usb_info.get("device_desc", "").strip()

    # Icom CP210x USB devices expose instance IDs like "IC-7300_03027544" or "IC-9700_13012430_A"
    # Note: Windows autogenerated instance IDs start with digits/hex & ampersands like "6&13fc6e5a&0&0000"
    model = ""
    serial_id = ""
    port_suffix = ""

    if inst and "&" not in inst:
        parts = inst.split("_")
        if parts and any(ch.isalpha() for ch in parts[0]):
            model = parts[0]
            if len(parts) >= 2:
                serial_id = parts[1]
            if len(parts) >= 3:
                port_suffix = parts[2]

    if not model and friendly:
        # Strip trailing "(COMx)" if present
        cleaned = re.sub(r"\s*\(COM\d+\)\s*$", "", friendly, flags=re.IGNORECASE).strip()
        model = cleaned or desc

    if not model:
        model = desc or "USB Serial Device"

    return {
        "usb_model": model,
        "usb_serial": serial_id,
        "usb_port_suffix": port_suffix,
        "usb_instance": inst,
        "usb_vidpid": usb_info.get("vidpid", ""),
        "usb_friendly": friendly,
    }


def list_serial_ports_with_usb() -> List[Dict[str, Any]]:
    """Enumerate available COM ports enriched with USB bus descriptor metadata."""
    reg_map = _read_usb_com_registry()
    ports: List[Dict[str, Any]] = []
    for p in sorted(serial.tools.list_ports.comports(), key=lambda x: (int(re.sub(r"\D", "", x.device) or 999), x.device)):
        usb_info = reg_map.get(p.device.upper(), {})
        parsed = extract_model_from_usb_bus(usb_info)
        if not parsed["usb_model"] or parsed["usb_model"] == "USB Serial Device":
            if p.serial_number and "&" not in p.serial_number:
                parsed["usb_model"] = p.serial_number.split("_")[0]
            elif p.product:
                parsed["usb_model"] = p.product
            elif p.description:
                parsed["usb_model"] = re.sub(r"\s*\(COM\d+\)\s*$", "", p.description, flags=re.IGNORECASE).strip()

        ports.append(
            {
                "port": p.device,
                "description": p.description or "",
                "hwid": p.hwid or "",
                **parsed,
            }
        )
    return ports


def get_preferred_hostapi_index() -> Optional[int]:
    """Prefer Windows DirectSound (untruncated names, reliable multi-stream 48 kHz without WdmSyncIoctl errors)."""
    try:
        hostapis = sd.query_hostapis()
        for idx, ha in enumerate(hostapis):
            if "DIRECTSOUND" in ha["name"].upper():
                return idx
        for idx, ha in enumerate(hostapis):
            if "MME" in ha["name"].upper():
                return idx
        for idx, ha in enumerate(hostapis):
            if "WASAPI" in ha["name"].upper():
                return idx
        return sd.default.hostapi
    except Exception:
        return None


def list_audio_devices() -> Dict[str, List[Dict[str, Any]]]:
    """List audio input and output devices from the preferred Windows Host API."""
    inputs: List[Dict[str, Any]] = []
    outputs: List[Dict[str, Any]] = []
    preferred_api = get_preferred_hostapi_index()

    try:
        devices = sd.query_devices()
    except Exception:
        return {"inputs": inputs, "outputs": outputs}

    for idx, d in enumerate(devices):
        if preferred_api is not None and d["hostapi"] != preferred_api:
            continue
        item = {
            "index": idx,
            "name": d["name"],
            "channels_in": int(d["max_input_channels"]),
            "channels_out": int(d["max_output_channels"]),
            "samplerate": float(d["default_samplerate"]),
        }
        if d["max_input_channels"] > 0:
            inputs.append(item)
        if d["max_output_channels"] > 0:
            outputs.append(item)

    return {"inputs": inputs, "outputs": outputs}


def find_audio_device_index(name: str, is_input: bool) -> Optional[int]:
    """Resolve a configured audio device name to its current PortAudio device index."""
    if not name:
        return None
    devices = list_audio_devices()["inputs" if is_input else "outputs"]
    name_low = name.strip().lower()
    for d in devices:
        if d["name"].strip().lower() == name_low:
            return d["index"]
    for d in devices:
        if name_low in d["name"].lower():
            return d["index"]
    return None


def auto_match_audio_device(usb_model: str, is_input: bool) -> Optional[Dict[str, Any]]:
    """Dynamically match a USB audio device to a radio's USB model string (e.g. 'IC-7300' -> 'ICOM 7300...')."""
    if not usb_model:
        return None
    devices = list_audio_devices()["inputs" if is_input else "outputs"]
    # Extract alphanumeric tokens like ["IC", "7300"] or ["9700"]
    tokens = [t for t in re.split(r"[^A-Za-z0-9]+", usb_model.upper()) if len(t) >= 2]
    numeric_tokens = [t for t in tokens if any(c.isdigit() for c in t)]

    best_score = 0
    best_dev = None
    for d in devices:
        dname = d["name"].upper()
        if "USB AUDIO" not in dname and "CODEC" not in dname and "ICOM" not in dname:
            continue
        score = 0
        for nt in numeric_tokens:
            if nt in dname:
                score += 10
        for t in tokens:
            if t in dname:
                score += 2
        if "ICOM" in dname:
            score += 1
        if score > best_score:
            best_score = score
            best_dev = d
    return best_dev if best_score >= 10 else None
